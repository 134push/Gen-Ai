# Assignment Operators Demo

x = 10

print("Starting Value:", x)

# += Add and Assign
x += 5
print("After += 5:", x)


# -= Subtract and Assign
x -= 3
print("After -= 3:", x)


# *= Multiply and Assign
x *= 2
print("After *= 2:", x)


# /= Divide and Assign
x /= 4
print("After /= 4:", x)


# %= Modulus and Assign
x %= 3
print("After %= 3:", x)


# **= Power and Assign
x = 5
x **= 2
print("After **= 2:", x)


# //= Floor Division and Assign
x = 10
x //= 2
print("After //= 2:", x)